create or replace function public.sync_settings_media_references()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  delete from public.media_references where resource_type='site_settings' and resource_id='global';
  if tg_op <> 'DELETE' then
    insert into public.media_references(media_id,resource_type,resource_id,field_name)
    select id,'site_settings','global','logo' from public.media_assets where public_url=new.logo_url and new.logo_url<>''
