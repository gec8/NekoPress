end $$;

create or replace function public.sync_new_media_asset_references()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  delete from public.media_references where media_id=new.id;
  insert into public.media_references(media_id,resource_type,resource_id,field_name)
  select new.id,'article',id::text,'cover' from public.articles where image_url=new.public_url and new.public_url<>''
  on conflict do nothing;
  insert into public.media_references(media_id,resource_type,resource_id,field_name)
  select new.id,'article',id::text,'content' from public.articles where new.public_url<>'' and position(new.public_url in content::text)>0
  on conflict do nothing;
  insert into public.media_references(media_id,resource_type,resource_id,field_name)
  select new.id,'moment',id::text,'image' from public.moments where image_url=new.public_url and new.public_url<>''
  on conflict do nothing;
  insert into public.media_references(media_id,resource_type,resource_id,field_name)
  select new.id,'carousel',id::text,'image' from public.carousel_items where image_url=new.public_url and new.public_url<>''
  on conflict do nothing;
  insert into public.media_references(media_id,resource_type,resource_id,field_name)
  select new.id,'site_settings','global','logo' from public.site_settings where logo_url=new.public_url and new.public_url<>''
  on conflict do nothing;
  insert into public.media_references(media_id,resource_type,resource_id,field_name)
  select new.id,'site_settings','global','default_cover' from public.site_settings where default_cover_url=new.public_url and new.public_url<>''
  on conflict do nothing;
  return new;
end $$;

