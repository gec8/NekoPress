create table if not exists public.media_assets (
  id uuid primary key default gen_random_uuid(),
  path text not null unique,
  public_url text not null unique,
  original_name text not null,
  mime_type text not null,
  media_type text not null check (media_type in ('image','audio','video')),
  size_bytes bigint not null default 0 check (size_bytes >= 0),
  width int check (width is null or width > 0),
  height int check (height is null or height > 0),
  duration_seconds numeric check (duration_seconds is null or duration_seconds >= 0),
  status text not null default 'ready' check (status in ('uploading','ready','failed','trash')),
  uploaded_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.media_references (
  id bigint generated by default as identity primary key,
  media_id uuid not null references public.media_assets(id) on delete cascade,
  resource_type text not null check (resource_type in ('article','moment','carousel','site_settings')),
  resource_id text not null,
  field_name text not null,
  created_at timestamptz not null default now(),
  unique (media_id, resource_type, resource_id, field_name)
);

create index if not exists media_assets_created_idx on public.media_assets(created_at desc);
create index if not exists media_assets_type_status_idx on public.media_assets(media_type,status,created_at desc);
create index if not exists media_references_media_idx on public.media_references(media_id);
create index if not exists media_references_resource_idx on public.media_references(resource_type,resource_id);

alter table public.media_assets enable row level security;
alter table public.media_references enable row level security;
revoke all on public.media_assets, public.media_references from anon, authenticated;
grant all on public.media_assets, public.media_references to service_role;
grant usage, select on all sequences in schema public to service_role;

create or replace function public.sync_article_media_references()
returns trigger language plpgsql security definer set search_path=public as $$
declare target_id text;
begin
  target_id := case when tg_op='DELETE' then old.id::text else new.id::text end;
  delete from public.media_references where resource_type='article' and resource_id=target_id;
  if tg_op <> 'DELETE' then
    insert into public.media_references(media_id,resource_type,resource_id,field_name)
    select id,'article',new.id::text,'cover' from public.media_assets where public_url=new.image_url and new.image_url<>''
    on conflict do nothing;
    insert into public.media_references(media_id,resource_type,resource_id,field_name)
    select id,'article',new.id::text,'content' from public.media_assets
    where public_url<>'' and position(public_url in new.content::text)>0
    on conflict do nothing;
  end if;
  if tg_op='DELETE' then return old; end if;
  return new;
end $$;

